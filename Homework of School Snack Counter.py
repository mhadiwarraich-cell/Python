# School Snack Counter

snacks = {"Chips", "Juice", "Cookies"}
snacks.add("Apple")

friend = {"Apple", "Juice", "Cake"}
print("Shared Snacks:", snacks.intersection(friend))

counts = [5, 3, 2]
counts.append(4)

print("Number of 3s:", counts.count(3))

counts.reverse()
print("Reversed Counts:", counts)